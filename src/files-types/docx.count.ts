import * as unzip from "unzipper";
import { parseString } from "xml2js";
import { FileNotCompatibleError } from "../errors/FileNotCompatibleError";
import { ICounter } from "./base.count";

const LAST_RENDERED_PAGE_BREAK = /<[A-Za-z0-9]+:lastRenderedPageBreak\b[^>]*\/?>/g;
const EXPLICIT_PAGE_BREAK =
  /<[A-Za-z0-9]+:br\b[^>]*\b[A-Za-z0-9]+:type\s*=\s*"page"[^>]*\/?>/g;
const SECTION_PROPERTIES =
  /<[A-Za-z0-9]+:sectPr\b[^>]*>[\s\S]*?<\/[A-Za-z0-9]+:sectPr>/g;
const CONTINUOUS_SECTION = /<[A-Za-z0-9]+:type\b[^>]*\b[A-Za-z0-9]+:val\s*=\s*"continuous"/;

function countMatches(xml: string, re: RegExp): number {
  const matches = xml.match(re);
  return matches ? matches.length : 0;
}

export class DocxCounter implements ICounter {
  /**
   * Reads the page count that Office writes in docProps/app.xml.
   * Returns undefined when the property is absent (files generated by
   * third-party libraries) or holds a non positive value.
   */
  private static async _pagesFromProps(xmlStr: string): Promise<number | undefined> {
    const result = await new Promise<any>((resolve) => {
      try {
        parseString(xmlStr, { explicitArray: true }, (err, parsed) => {
          resolve(err ? undefined : parsed);
        });
      } catch (error) {
        resolve(undefined);
      }
    });

    if (!result || typeof result !== "object") {
      return undefined;
    }

    // Namespace prefixes are not guaranteed, compare on the local name.
    const propertiesKey = Object.keys(result).find((key) => /(^|:)Properties$/.test(key));
    const properties = propertiesKey ? result[propertiesKey] : undefined;
    if (!properties || typeof properties !== "object") {
      return undefined;
    }

    const pagesKey = Object.keys(properties).find((key) => /(^|:)Pages$/.test(key));
    const rawPages = pagesKey ? properties[pagesKey] : undefined;
    const pages = parseInt(String(Array.isArray(rawPages) ? rawPages[0] : rawPages), 10);

    return Number.isFinite(pages) && pages > 0 ? pages : undefined;
  }

  /**
   * Best effort page count straight from the document body, used when
   * docProps/app.xml has no usable Pages value. Word stores pagination
   * hints (lastRenderedPageBreak) on save; explicit page breaks and
   * section breaks are counted as a fallback.
   */
  private static _pagesFromDocumentXml(documentXml: string): number {
    const renderedBreaks = countMatches(documentXml, LAST_RENDERED_PAGE_BREAK);
    if (renderedBreaks > 0) {
      return renderedBreaks + 1;
    }

    const explicitBreaks = countMatches(documentXml, EXPLICIT_PAGE_BREAK);
    const sections = documentXml.match(SECTION_PROPERTIES) || [];
    // The last sectPr holds the body properties and does not start a new page,
    // continuous sections do not break the page either.
    const sectionBreaks = sections.filter(
      (section) => !CONTINUOUS_SECTION.test(section)
    ).length;
    const effectiveSectionBreaks = Math.max(0, sectionBreaks - 1);

    return 1 + explicitBreaks + effectiveSectionBreaks;
  }

  static async count(buffer: Uint8Array | Buffer): Promise<number> {
    let directory: any;

    try {
      directory = await unzip.Open.buffer(Buffer.from(buffer));
    } catch (error) {
      throw new FileNotCompatibleError();
    }

    const files = (directory && directory.files) || [];
    const propsFile = files.find((file: any) => file.path === "docProps/app.xml");
    const documentFile = files.find((file: any) => file.path === "word/document.xml");

    if (!propsFile && !documentFile) {
      throw new FileNotCompatibleError();
    }

    let propsPages: number | undefined;
    if (propsFile) {
      try {
        propsPages = await DocxCounter._pagesFromProps(
          (await propsFile.buffer()).toString("utf8")
        );
      } catch (error) {
        propsPages = undefined;
      }
    }

    let structuralPages = 0;
    if (documentFile) {
      try {
        structuralPages = DocxCounter._pagesFromDocumentXml(
          (await documentFile.buffer()).toString("utf8")
        );
      } catch (error) {
        structuralPages = 0;
      }
    }

    const pages = Math.max(propsPages || 0, structuralPages);

    if (pages < 1) {
      throw new FileNotCompatibleError();
    }

    return pages;
  }
}
